#!/usr/bin/env python3
"""Renders docs/PERFORMANCE_REPORT.md from perf_driver.py's JSON plus facts about this machine.

Every number comes from the JSON or from a command run here; a missing/null value renders as
"NOT MEASURED" and never as a guess. Hand-written analysis lives in tests/performance/findings.md
and is appended verbatim.
Usage: render_report.py --results r.json --bin PATH --out report.md [--budgets b.json] [--findings f.md]
"""
import argparse
import datetime
import json
import os
import platform
import subprocess
import time
from pathlib import Path

NA = "NOT MEASURED"
STARTUP_RUNS = 30


def sh(*cmd):
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=20).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return ""


def cpu_model():
    try:
        for line in open("/proc/cpuinfo"):
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return NA


def mem_gib():
    try:
        for line in open("/proc/meminfo"):
            if line.startswith("MemTotal"):
                return "%.1f GiB" % (int(line.split()[1]) / 1048576.0)
    except OSError:
        pass
    return NA


def os_pretty():
    try:
        for line in open("/etc/os-release"):
            if line.startswith("PRETTY_NAME="):
                return line.split("=", 1)[1].strip().strip('"')
    except OSError:
        pass
    return NA


def startup_version_ms(binary):
    lat = []
    for _ in range(STARTUP_RUNS):
        t0 = time.perf_counter()
        subprocess.run([binary, "--version"], capture_output=True)
        lat.append((time.perf_counter() - t0) * 1000.0)
    lat.sort()
    return lat[0], lat[len(lat) // 2], lat[int(len(lat) * 0.95) - 1], lat[-1]


def f(v, unit="", digits=None):
    if v is None:
        return NA
    if digits is not None:
        v = round(v, digits)
    return "%s%s" % (v, unit)


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def render(args):
    doc = json.loads(Path(args.results).read_text())
    meta, results = doc["meta"], doc["results"]
    binary = args.bin
    size = os.stat(binary).st_size
    smin, smed, sp95, smax = startup_version_ms(binary)
    virt = "WSL2 (virtualised; timings noisier than bare metal)" if "microsoft" in platform.release().lower() else "native"
    docker_v = sh("docker", "version", "--format", "{{.Server.Version}}") or NA
    py = platform.python_version()
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    msgs = meta["messages_per_account"]

    L = []
    L.append("# OpenMail performance report\n")
    L.append("Generated by `scripts/perf.sh` (driver `tests/performance/perf_driver.py`, renderer "
             "`tests/performance/render_report.py`) on %s. Every figure below was measured by running the real "
             "`openmail-mcp` release binary as an MCP stdio server against a real GreenMail IMAP server; "
             "anything that could not be measured says `%s`. Re-run `scripts/perf.sh` to refresh.\n" % (now, NA))

    L.append("## Environment\n")
    L.append(table(["Item", "Value"], [
        ["CPU", "%s (%s threads)" % (cpu_model(), os.cpu_count())],
        ["RAM", mem_gib()],
        ["OS / kernel", "%s / %s" % (os_pretty(), platform.release())],
        ["Virtualisation", virt],
        ["rustc (toolchain that built the binary)", args.rustc or NA],
        ["Binary", "`%s`, %s, built from commit `%s`" % (os.path.basename(binary), sh(binary, "--version") or NA,
                                                        args.commit or NA)],
        ["Build profile", args.profile or NA],
        ["Mail server", "GreenMail 2.1.3 (%s) in Docker %s, default bridge network, IMAP port published via docker's userland proxy" % (meta["greenmail_image"], docker_v)],
        ["TLS", "the binary refuses plain IMAP, so an asyncio TLS-terminating proxy (private CA via `SSL_CERT_FILE`, no verification disabled) sits between binary and GreenMail; its latency and CPU are inside every latency figure and are NOT in the binary's CPU/RSS figures"],
        ["Load generator", "Python %s asyncio MCP client on the same host (shares CPU with everything above)" % py],
        ["Mailbox size", "%d messages per account in INBOX, 2231-2272 bytes (~2.2 KiB) each (plain text, one message in 10 contains the search keyword, so a search has exactly %d hits); the largest scale point holds %d messages in total" % (msgs, msgs // 10, max(r["accounts"] for r in results) * msgs)],
        ["Limits", "defaults: 2 IMAP sessions per account, **global cap 8** (`[limits] max_global_connections`)"],
    ]))
    L.append("")

    L.append("## Binary\n")
    L.append(table(["Metric", "Value", "Method"], [
        ["Binary size (release)", "%.2f MiB (%d bytes)" % (size / 1048576.0, size), "`stat -c %s`"],
        ["`--version` wall time", "min %.2f / median %.2f / p95 %.2f / max %.2f ms" % (smin, smed, sp95, smax),
         "%d runs incl. fork+exec; a floor, loads no config" % STARTUP_RUNS],
    ]))
    L.append("")

    L.append("## Scale results (1 / 10 / 50 / 100 configured accounts)\n")
    cols = [("Metric", lambda r: None)]
    rows = [
        ("Startup → `initialize` answered (ms)", lambda r: f(r["startup_to_initialize_ms"])),
        ("IMAP sessions opened by startup", lambda r: f(r["sessions_opened_by_startup"])),
        ("Idle RSS, nothing used yet (MiB)", lambda r: f(r["idle_rss_untouched_mib"])),
        ("Idle RSS after every account was used once (MiB)", lambda r: f(r["idle_rss_after_all_accounts_mib"])),
        ("Idle IMAP sessions left open after that", lambda r: f(r["idle_sessions_after_all_accounts"])),
        ("Cold connection (TCP+TLS+LOGIN+LIST) p50 / p95 (ms)", lambda r: "%s / %s (n=%s, failed %s)" % (
            f(r["cold_connect"]["p50_ms"]), f(r["cold_connect"]["p95_ms"]), r["cold_connect"]["samples"], r["cold_connect"]["failed"])),
        ("GreenMail alone: `SEARCH TEXT` p50 / p95 (ms)", lambda r: "%s / %s" % (
            f(r.get("greenmail_floor", {}).get("search_text_p50_ms")), f(r.get("greenmail_floor", {}).get("search_text_p95_ms")))),
        ("Search, one at a time, p50 / p95 (ms)", lambda r: "%s / %s (n=%s, wrong hit counts %s)" % (
            f(r["search_serial"]["p50_ms"]), f(r["search_serial"]["p95_ms"]), r["search_serial"]["samples"], r["search_serial"]["wrong_hit_count"])),
        ("Mixed load: requests (50% search / 50% get_message), in flight", lambda r: "%s, %s, errors %s %s" % (
            r["load"]["requests"], r["load"]["concurrency"], r["load"]["errors"], r["load"].get("error_codes") or "")),
        ("Mixed load: search p50 / p95 (ms)", lambda r: "%s / %s" % (f(r["load"]["search_p50_ms"]), f(r["load"]["search_p95_ms"]))),
        ("Mixed load: get_message p50 / p95 (ms)", lambda r: "%s / %s" % (f(r["load"]["get_message_p50_ms"]), f(r["load"]["get_message_p95_ms"]))),
        ("Mixed load: requests/s · messages returned/s", lambda r: "%s · %s" % (f(r["load"]["requests_per_s"]), f(r["load"]["messages_returned_per_s"]))),
        ("Mixed load: CPU of the binary (% of one core, whole phase)", lambda r: f(r["load"]["cpu_percent_of_one_core"])),
        ("Peak RSS under load (MiB, VmHWM)", lambda r: f(r["load"]["peak_rss_mib_vmhwm"])),
        ("Peak threads", lambda r: f(r["load"]["peak_threads"])),
        ("Sockets opened during the load phase (connection churn)", lambda r: f(r["load"]["sessions_accepted_during_load"])),
    ]
    L.append(table(["Metric"] + ["N=%d" % r["accounts"] for r in results],
                   [[name] + [fn(r) for r in results] for name, fn in rows]))
    L.append("")

    L.append("## Global IMAP session cap (default 8) with many accounts configured\n")
    L.append("Peak simultaneous IMAP sessions, counted exactly at the TLS proxy (connect/close events) and cross-checked "
             "by sampling `ESTABLISHED` sockets in `/proc/net/tcp` every 20 ms (the data `ss -tn` prints) on the proxy's port "
             "and on GreenMail's published port.\n")
    L.append(table(["Accounts", "Phase", "In flight", "Peak sessions (proxy, exact)", "Peak (kernel, GreenMail port)", "Cap held (≤ 8)"], [
        row for r in results for row in (
            [r["accounts"], "mixed load", r["load"]["concurrency"], r["load"]["peak_sessions_proxy"],
             r["load"]["peak_sessions_kernel_greenmail_port"], "yes" if r["load"]["peak_sessions_proxy"] <= r["global_cap"] else "**NO**"],
            [r["accounts"], "burst: one search to every account at once", r["burst_all_accounts"]["in_flight"],
             r["burst_all_accounts"]["peak_sessions_proxy"], r["burst_all_accounts"]["peak_sessions_kernel_greenmail_port"],
             "yes" if r["burst_all_accounts"]["peak_sessions_proxy"] <= r["global_cap"] else "**NO**"])
    ]))
    L.append("")

    L.append("## Server rate limiter (sustained throughput ceiling)\n")
    L.append("400 `mail_list_folders` calls fired at once after the limiter's buckets were full. The limits are "
             "compile-time constants (`crates/openmail-mcp/src/access.rs`: global burst 120 + 20/s, per account burst 60 + 10/s).\n")
    L.append(table(["Accounts", "ok", "rejected", "wall (s)", "ok/s over the probe"], [
        [r["accounts"], r["rate_limit_probe"]["ok"], r["rate_limit_probe"]["error_codes"], r["rate_limit_probe"]["wall_s"],
         r["rate_limit_probe"]["ok_per_s"]] if "rate_limit_probe" in r else [r["accounts"], NA, NA, NA, NA] for r in results]))
    L.append("")

    L.append("## Recovery after `docker kill` + `docker start` of GreenMail mid-run\n")
    L.append("Four paced workers (one search every 0.4 s each) run throughout. GreenMail keeps users and mail in memory, so "
             "the restart yields an empty server; users are recreated through its REST API before the first call can succeed.\n")
    rec_rows = []
    for r in results:
        c = r.get("recovery")
        if not c:
            rec_rows.append([r["accounts"]] + [NA] * 7)
            continue
        rec_rows.append([r["accounts"], "yes" if c["process_survived"] else "**NO**", f(c["kill_to_port_ready_s"], " s"),
                         f(c["users_restored_after_port_ready_s"], " s"), f(c["recovery_after_server_ready_s"], " s"),
                         f(c["kill_to_first_success_s"], " s"), c["failed_calls_during_outage"], f(c["slowest_failed_call_s"], " s")])
    L.append(table(["Accounts", "Binary survived", "kill → IMAP port ready", "users restored (after port)",
                    "server fully ready → first OK call", "kill → first OK call (total)", "calls failed during outage",
                    "slowest failed call"], rec_rows))
    L.append("")

    L.append("## Shutdown\n")
    L.append(table(["Accounts", "exit status on stdin EOF", "time to exit (ms)"],
                   [[r["accounts"], r["shutdown"]["exit"], f(r["shutdown"]["ms"])] for r in results]))
    L.append("")

    if args.budgets and Path(args.budgets).exists():
        b = json.loads(Path(args.budgets).read_text())
        L.append("## Budgets (`tests/performance/budgets.json`)\n")
        L.append("Derived from the baseline above: measured value × 1.5, rounded up (the session cap is the configured cap, "
                 "unscaled). `scripts/perf.sh --check` re-runs the matrix and fails if any figure exceeds its budget. "
                 "Budgets are host-specific; regenerate with `scripts/perf.sh --write-budgets` when the reference machine changes.\n")
        keys = ["startup_to_initialize_ms", "idle_rss_after_all_accounts_mib", "peak_rss_mib_vmhwm",
                "search_serial_p95_ms", "load_search_p95_ms", "peak_sessions"]
        L.append(table(["Metric"] + ["N=%s" % n for n in b], [[k] + [b[n].get(k, NA) for n in b] for k in keys]))
        L.append("")

    if args.findings and Path(args.findings).exists():
        L.append(Path(args.findings).read_text().rstrip() + "\n")

    L.append("## Not measured / limits\n")
    L.append("- Only GreenMail was measured, behind a TLS proxy, on one WSL2 host, with the load generator on the same machine. "
             "No real provider (Gmail, Microsoft 365, Dovecot) and no WAN latency: connection/search numbers are lower bounds.\n"
             "- One run per scale point; no repeated-run variance. Treat differences under ~20%% as noise on WSL2.\n"
             "- The binary's CPU is read from `/proc/<pid>/stat`; the proxy, GreenMail and load generator are not included in it.\n"
             "- Mailboxes hold %d small text messages per account; large mailboxes (100k+ messages), large attachments and HTML-heavy mail were not measured.\n"
             "- Only read tools were exercised (the product has no draft/send tools yet). SMTP performance is NOT MEASURED.\n"
             "- Sustained multi-hour memory growth (leaks) was not measured; the figures cover seconds-to-minutes runs.\n"
             "- Windows and macOS binaries were not measured.\n" % msgs)
    Path(args.out).write_text("\n".join(L))


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--results", required=True)
    p.add_argument("--bin", required=True)
    p.add_argument("--out", required=True)
    p.add_argument("--budgets")
    p.add_argument("--rustc", default="")
    p.add_argument("--commit", default="")
    p.add_argument("--profile", default="")
    p.add_argument("--findings")
    render(p.parse_args())


if __name__ == "__main__":
    main()
