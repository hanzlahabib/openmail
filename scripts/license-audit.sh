#!/usr/bin/env bash
# License audit: regenerates THIRD_PARTY_LICENSES.md from Cargo.lock and checks
# that every third-party dependency can be used under an MIT-compatible license.
# Usage: scripts/license-audit.sh [--check]
#   (default)  rewrite THIRD_PARTY_LICENSES.md, then run the checks
#   --check    do not write; fail if THIRD_PARTY_LICENSES.md is stale
# Env: OPENMAIL_CARGO_TOOLCHAIN=stable  (optional rustup toolchain override)
# Exit codes: 0 ok, 1 incompatible/unknown license or stale file, 2 tooling missing.
# Results describe the current Cargo.lock only; re-run after any dependency change.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

check_only=0
if [[ "${1:-}" == "--check" ]]; then
  check_only=1
fi

for tool in python3 cargo; do
  command -v "$tool" >/dev/null 2>&1 || { echo "license-audit.sh: $tool not found" >&2; exit 2; }
done

cargo_cmd=(cargo)
if [[ -n "${OPENMAIL_CARGO_TOOLCHAIN:-}" ]]; then
  cargo_cmd=(cargo "+${OPENMAIL_CARGO_TOOLCHAIN}")
fi

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

"${cargo_cmd[@]}" metadata --format-version 1 --locked > "$tmp/meta.json"

status=0
python3 - "$tmp/meta.json" "$tmp/THIRD_PARTY_LICENSES.md" <<'PY' || status=$?
import json
import re
import sys

meta_path, out_path = sys.argv[1], sys.argv[2]
meta = json.load(open(meta_path))
workspace = set(meta["workspace_members"])

# SPDX ids that cannot be combined into an MIT-licensed distribution unless an
# OR alternative avoids them.
COPYLEFT = re.compile(r"^(A?GPL|LGPL|SSPL|EUPL|OSL|CPAL|BUSL|CC-BY-(NC|SA))", re.I)


def tokens(expr):
    return re.findall(r"\(|\)|[^\s()]+", expr.replace("/", " OR "))


def ok(expr):
    """Evaluate an SPDX expression: True if some permitted choice is non-copyleft."""
    toks = tokens(expr)
    pos = 0

    def parse_or():
        nonlocal pos
        val = parse_and()
        while pos < len(toks) and toks[pos].upper() == "OR":
            pos += 1
            rhs = parse_and()
            val = val or rhs
        return val

    def parse_and():
        nonlocal pos
        val = parse_atom()
        while pos < len(toks) and toks[pos].upper() == "AND":
            pos += 1
            rhs = parse_atom()
            val = val and rhs
        return val

    def parse_atom():
        nonlocal pos
        tok = toks[pos]
        pos += 1
        if tok == "(":
            val = parse_or()
            pos += 1  # closing paren
            return val
        if tok.upper() == "WITH":  # exception id follows; ignore
            pos += 1
            return True
        return not COPYLEFT.match(tok)

    return parse_or()


rows, bad, flagged = [], [], []
for pkg in meta["packages"]:
    if pkg["id"] in workspace:
        continue
    lic = pkg.get("license")
    if not lic:
        lic = "UNKNOWN (no SPDX license field)"
        bad.append((pkg["name"], pkg["version"], lic))
    elif not ok(lic):
        bad.append((pkg["name"], pkg["version"], lic))
    elif COPYLEFT.search(lic):
        flagged.append((pkg["name"], pkg["version"], lic))
    rows.append((pkg["name"], pkg["version"], lic, pkg.get("repository") or ""))

rows.sort(key=lambda r: (r[0].lower(), r[1]))
with open(out_path, "w") as out:
    out.write("# Third-party licenses\n\n")
    out.write(
        "Generated by `scripts/license-audit.sh` from `Cargo.lock` (all features, all targets). "
        "Do not edit by hand. Valid for the current lockfile only; "
        f"{len(rows)} third-party crates.\n\n"
    )
    out.write("| Crate | Version | License (SPDX) | Repository |\n|---|---|---|---|\n")
    for name, ver, lic, repo in rows:
        out.write(f"| {name} | {ver} | {lic} | {repo} |\n")

for name, ver, lic in bad:
    print(f"INCOMPATIBLE/UNKNOWN: {name} {ver}: {lic}", file=sys.stderr)
for name, ver, lic in flagged:
    print(f"note (copyleft only in an optional OR branch): {name} {ver}: {lic}")
print(f"{len(rows)} crates, {len(bad)} incompatible/unknown")
sys.exit(1 if bad else 0)
PY

if [[ $check_only -eq 1 ]]; then
  diff -u THIRD_PARTY_LICENSES.md "$tmp/THIRD_PARTY_LICENSES.md" >/dev/null \
    || { echo "license-audit.sh: THIRD_PARTY_LICENSES.md is stale; run scripts/license-audit.sh" >&2; exit 1; }
else
  cp "$tmp/THIRD_PARTY_LICENSES.md" THIRD_PARTY_LICENSES.md
fi

if command -v cargo-deny >/dev/null 2>&1; then
  echo "== cargo deny check licenses =="
  "${cargo_cmd[@]}" deny --locked check licenses
else
  echo "license-audit.sh: cargo-deny not installed; skipped allow-list check" >&2
fi
exit "$status"
